async function S(d, p, u, r) {
  let t = d.flatMap((a) => a.result.items),
    n = d.flatMap((a) => a.result.unmappable),
    g = t.filter(iPe),
    m = J(t, (a) => mce(a) === "project"),
    h = J(t, (a) => mce(a) === "warned"),
    c = [],
    i = 0;
  for (let a of g)
    try {
      let y = await a.apply({ dryRun: p, storageV5: r });
      if (typeof y === "string") (c.push(`  \u2713 ${pw(y)}`), i++);
      else c.push(`  - skipped ${pw(y.skipped)}`);
    } catch (y) {
      c.push(`  \u2717 ${ID(a.label)}: ${pw(l(y))}`);
    }
  let o = !1;
  if (n.length > 0)
    try {
      let a = await BVe(
        d.map((y) => ({
          sourceId: y.sourceId,
          displayName: y.displayName,
          unmappable: y.result.unmappable,
        })),
        { dryRun: p },
      );
      if (typeof a === "string") (c.push(`  \u2713 ${pw(a)}`), (o = !0));
      else c.push(`  - skipped ${pw(a.skipped)}`);
    } catch (a) {
      c.push(`  \u2717 fallback skill: ${pw(l(a))}`);
    }
  s("tengu_import_apply", { imported: i, dry_run: p ? 1 : 0 });
  let e = p
      ? `Dry run \u2014 would import ${i} ${R(i, "item")}:`
      : `Imported ${i} ${R(i, "item")}:`,
    f = [];
  if (h > 0)
    f.push(
      `  \u26A0 ${h} warning-flagged ${R(h, "item")} held back \u2014 run \`claude import\` from a terminal to review.`,
    );
  if (m > 0)
    f.push(
      `  \u26A0 ${m} project-level ${R(m, "item")} held back \u2014 run \`claude import\` from a terminal to review.`,
    );
  let w = [
    ...u.map((a) => `  \u26A0 ${a}`),
    ...(f.length > 0 ? ["", ...f] : []),
    ...(o && !p
      ? ["", "Run /import-to-claude-code to finish the unmapped items interactively."]
      : []),
  ];
  return [e, ...c, ...w].join(`
`);
}
